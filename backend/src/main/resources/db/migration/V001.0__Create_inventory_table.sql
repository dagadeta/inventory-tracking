CREATE SCHEMA IF NOT EXISTS inventory
    AUTHORIZATION ${flyway:user};

CREATE TABLE IF NOT EXISTS inventory.users (
    id int8 GENERATED BY DEFAULT AS IDENTITY( INCREMENT BY 1 MINVALUE 1 MAXVALUE 9223372036854775807 START 1 CACHE 1 NO CYCLE) NOT NULL,
    "role" int2 NOT NULL,
    username varchar(255) NOT NULL,
    password varchar(255) NOT NULL,
    CONSTRAINT users_pkey PRIMARY KEY (id),
    CONSTRAINT users_role_check CHECK (((role >= 0) AND (role <= 1)))
);

CREATE TABLE IF NOT EXISTS inventory.items (
    id int8 GENERATED BY DEFAULT AS IDENTITY( INCREMENT BY 1 MINVALUE 1 MAXVALUE 9223372036854775807 START 1 CACHE 1 NO CYCLE) NOT NULL,
    amount int4 NOT NULL,
    "name" varchar(255) NOT NULL,
    CONSTRAINT items_pkey PRIMARY KEY (id)
);

CREATE TABLE inventory.item_lent (
    id int8 GENERATED BY DEFAULT AS IDENTITY( INCREMENT BY 1 MINVALUE 1 MAXVALUE 9223372036854775807 START 1 CACHE 1 NO CYCLE) NOT NULL,
    lent_to varchar(255) NOT NULL,
    "timestamp" timestamp(6) NOT NULL,
    item_id int8 NOT NULL,
    lent_by_id int8 NOT NULL,
    CONSTRAINT item_lent_pkey PRIMARY KEY (id)
);

ALTER TABLE inventory.item_lent ADD CONSTRAINT item_fkey FOREIGN KEY (item_id) REFERENCES inventory.items(id);
ALTER TABLE inventory.item_lent ADD CONSTRAINT lent_by_fkey FOREIGN KEY (lent_by_id) REFERENCES inventory.users(id);
